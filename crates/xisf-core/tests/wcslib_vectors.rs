/// Angular separation in degrees, by the haversine formula.
///
/// Not the arccos of a dot product: near zero separation that loses about half
/// its digits and bottoms out around 1.5e-8 radians, which is 3 milliarcseconds
/// and looks exactly like a real disagreement.
fn separation(a: [f64; 2], b: [f64; 2]) -> f64 {
    let (ra1, dec1) = (a[0].to_radians(), a[1].to_radians());
    let (ra2, dec2) = (b[0].to_radians(), b[1].to_radians());
    let dd = (dec2 - dec1) / 2.0;
    let dr = (ra2 - ra1) / 2.0;
    let h = dd.sin().powi(2) + dec1.cos() * dec2.cos() * dr.sin().powi(2);
    (2.0 * h.sqrt().clamp(-1.0, 1.0).asin()).to_degrees()
}

#[test]
fn every_projection_agrees_with_wcslib() {
    // The conformance tolerance, converted to degrees at this plate scale.
    const SCALE: f64 = 0.0005;
    const TOLERANCE: f64 = 1e-6 * SCALE;

    let mut worst = 0.0f64;
    let mut checked = 0;
    for (name, points) in WCSLIB {
        let system = ProjectionSystem::parse(name).unwrap_or_else(|| panic!("{name}"));
        let rotation = Rotation::new(REFERENCE_CELESTIAL, system.default_reference_native(), None)
            .unwrap_or_else(|| panic!("{name}: no rotation"));

        for &(x, y, ra, dec) in *points {
            let dx = x - REFERENCE_IMAGE[0];
            let dy = y - REFERENCE_IMAGE[1];
            let plane = [CD[0][0] * dx + CD[0][1] * dy, CD[1][0] * dx + CD[1][1] * dy];
            let native = deproject(plane, system)
                .unwrap_or_else(|| panic!("{name}: ({x}, {y}) left the projection's domain"));
            let got = native_to_celestial(native, rotation);

            let error = separation(got, [ra, dec]);
            worst = worst.max(error);
            checked += 1;
            assert!(
                error < TOLERANCE,
                "{name} at ({x}, {y}): got {got:?}, wcslib says [{ra}, {dec}], \
                 which is {:.3e} pixels apart",
                error / SCALE
            );
        }
    }

    assert!(checked >= 150, "only {checked} points were compared");
    // Comfortably inside the tolerance rather than scraping past it, which is
    // what says the formulas agree rather than merely nearly agree.
    assert!(worst / SCALE < 1e-7, "the worst disagreement was {:.3e} pixels", worst / SCALE);
}
