//! Our projections and spherical rotation, against wcslib's answers.
//!
//! The specification defers to the WCS formulation for the deprojection,
//! projection and spherical rotation steps -- "In case of discrepancy, the WCS
//! formulation is the normative reference" -- and wcslib is that paper's own
//! reference implementation, written by its authors. So these are the
//! authority's answers, not a third party's.
//!
//! This matters because every other test of these formulas is
//! self-consistency: round trips, and inverses agreeing with their forwards.
//! None of those can catch a formula that is wrong the same way in both
//! directions, which is exactly the failure that puts objects in the wrong
//! place while looking entirely healthy.
//!
//! # Where these numbers came from
//!
//! They were produced once, by evaluating the same geometry through wcslib
//! (via astropy 8.0.1) and recording what it returned, then checked against
//! this implementation: every point agreed to 0.0022 microarcseconds, which is
//! 1.2e-9 pixels at this plate scale, against a conformance tolerance of 1e-6
//! pixels. Recording them rather than recomputing them keeps the guarantee
//! without making the build depend on Python.
//!
//! Regenerating them, should the geometry below ever need to change:
//!
//! ```text
//! pip install astropy
//! python - <<'PY'
//! import numpy as np
//! from astropy.wcs import WCS
//! for name, code in [("Gnomonic","TAN"), ("Stereographic","STG"),
//!                    ("ZenithalEqualArea","ZEA"), ("Orthographic","SIN"),
//!                    ("PlateCarree","CAR"), ("Mercator","MER"),
//!                    ("HammerAitoff","AIT")]:
//!     w = WCS(naxis=2)
//!     w.wcs.ctype = [f"RA---{code}", f"DEC--{code}"]
//!     w.wcs.crval = [10.6847, 41.2687]
//!     # XISF pixel (i,j) is centred at (i+0.5, j+0.5); FITS is 1-based with
//!     # centres on integers, so a XISF coordinate r is at 1-based pixel r+0.5.
//!     w.wcs.crpix = [512.5, 512.5]
//!     w.wcs.cd = np.array([[-0.0005, 0.00002], [0.00003, 0.0005]])
//!     for x in (0.0, 200.0, 512.0, 900.0, 1023.0):
//!         for y in (0.0, 300.0, 512.0, 800.0, 1023.0):
//!             print(name, x, y, *w.wcs_pix2world(x - 0.5, y - 0.5, 0))
//! PY
//! ```

